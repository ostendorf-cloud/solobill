-- files holds the metadata of every object in the S3 compatible store:
-- receipts, imported originals, the logo and the stored PDF of an issued
-- document (issue #75; docs/concepts/solobill.md, "Receipt storage and
-- GoBD"). PostgreSQL is the authority. The bytes live in the store under
-- object_key, and sha256 and size_bytes are what every read is verified
-- against.
--
-- A row is written once. The primary control is the grant in
-- docker/postgres/grants/20261121150000_files.sql: the application role
-- gets SELECT and INSERT, never UPDATE, DELETE or TRUNCATE. The two
-- triggers below are defence in depth on top of that grant: a row trigger
-- refuses UPDATE and DELETE, and a statement trigger refuses TRUNCATE, for
-- any role, the table owner included. They do not stop the owner or a
-- superuser who disables or drops them on purpose (ALTER TABLE ... DISABLE
-- TRIGGER, DROP TABLE): that needs the table owner's role, which the
-- application never connects as.
CREATE TABLE files (
    -- Generated by the application, because the object key embeds it and
    -- the object is stored before the row is inserted.
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES tenants (id),
    purpose text NOT NULL,
    -- "<tenant id>/<file id>", never derived from the client file name.
    -- files_object_key_shape below enforces exactly that.
    object_key text NOT NULL,
    -- The version id the store returned, NULL on an unversioned bucket.
    object_version_id text,
    -- Lowercase hex SHA-256 of the bytes, computed by the server while
    -- streaming the upload.
    sha256 text NOT NULL,
    size_bytes bigint NOT NULL,
    -- Sniffed from the magic bytes, never taken from the client.
    content_type text NOT NULL,
    -- The client's file name as data for display only. Never a path or a
    -- key.
    original_filename text NOT NULL DEFAULT '',
    uploaded_by uuid,
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    -- The object lock retention the store confirmed, NULL without lock.
    retain_until timestamptz,
    CONSTRAINT files_purpose_check
        CHECK (purpose IN ('receipt', 'logo', 'import_original', 'document_pdf')),
    CONSTRAINT files_object_key_shape
        CHECK (object_key = tenant_id::text || '/' || id::text),
    CONSTRAINT files_sha256_shape CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT files_size_positive CHECK (size_bytes > 0),
    CONSTRAINT files_content_type_check
        CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'application/xml')),
    CONSTRAINT files_original_filename_length CHECK (char_length(original_filename) <= 255),
    -- The same composite target accounts_tenant_id_id_unique exists for:
    -- a later table (expenses.file_id, other_income.file_id) can reference
    -- (tenant_id, id) so a row cannot point at a file of another tenant.
    CONSTRAINT files_tenant_id_id_unique UNIQUE (tenant_id, id),
    -- An uploader of another tenant cannot be referenced. A NULL
    -- uploaded_by (a file written by a background job) skips the check.
    CONSTRAINT files_uploaded_by_fkey FOREIGN KEY (tenant_id, uploaded_by)
        REFERENCES accounts (tenant_id, id)
);

-- The duplicate warning of POST /api/v1/files looks files up by hash.
CREATE INDEX files_tenant_sha256_idx ON files (tenant_id, sha256);

CREATE FUNCTION files_block_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'files rows are written once and never changed or deleted'
        USING ERRCODE = 'insufficient_privilege';
END;
$$;

CREATE TRIGGER files_block_mutation
    BEFORE UPDATE OR DELETE ON files
    FOR EACH ROW EXECUTE FUNCTION files_block_mutation();

-- A row trigger does not fire on TRUNCATE, so it gets its own.
CREATE TRIGGER files_block_truncate
    BEFORE TRUNCATE ON files
    FOR EACH STATEMENT EXECUTE FUNCTION files_block_mutation();

-- Row level security, the same policy shape as every other tenant scoped
-- table: see 20261112233249_create_accounts.sql for why ENABLE and FORCE
-- are both needed and why NULLIF folds a reverted setting to NULL.
ALTER TABLE files ENABLE ROW LEVEL SECURITY;
ALTER TABLE files FORCE ROW LEVEL SECURITY;

CREATE POLICY files_tenant_isolation ON files
    USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
    WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

