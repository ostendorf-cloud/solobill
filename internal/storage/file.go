package storage

import (
	"time"

	"github.com/google/uuid"
)

// FilePurpose is what an uploaded file is for.
type FilePurpose string

const (
	// FilePurposeReceipt is a Beleg behind an expense or other income.
	FilePurposeReceipt FilePurpose = "receipt"
	// FilePurposeLogo is the seller logo printed on documents.
	FilePurposeLogo FilePurpose = "logo"
	// FilePurposeImportOriginal is the original PDF of an imported
	// historic document.
	FilePurposeImportOriginal FilePurpose = "import_original"
)

// File is the metadata row of one object in the S3 compatible store.
// The bytes live in the store under ObjectKey. PostgreSQL holds the
// authority: SHA256 and SizeBytes are written once at upload.
//
// The primary control is the grant: the application role gets SELECT
// and INSERT on files, never UPDATE or DELETE, so no row can change
// once written, linked or not. A link aware trigger is optional defence
// in depth only: it sees expenses.file_id and other_income.file_id, but
// not a link that lives only inside a frozen payload (the original of an
// imported document, the logo hash), which the grant alone protects.
// Issue #75 (I9) creates the table; see docs/concepts/solobill.md,
// "Receipt storage and GoBD".
type File struct {
	ID       uuid.UUID
	TenantID uuid.UUID
	Purpose  FilePurpose
	// ObjectKey is generated by solobill ("<tenant id>/<file id>"),
	// never derived from the uploaded filename.
	ObjectKey string
	// ObjectVersionID is the version id the store returned on upload,
	// nil when the bucket has no versioning.
	ObjectVersionID *string
	// SHA256 is the lowercase hex SHA-256 of the bytes, computed while
	// streaming the upload. A download recomputes it and refuses on a
	// mismatch.
	SHA256    string
	SizeBytes int64
	// ContentType is sniffed from the magic bytes, never taken from the
	// client: application/pdf, image/jpeg, image/png or application/xml.
	ContentType string
	// OriginalFilename is the client's filename, kept as data for display
	// only. It is never used as a path or an object key.
	OriginalFilename string
	UploadedBy       *uuid.UUID
	UploadedAt       time.Time
	// RetainUntil is the object lock retention date the store confirmed,
	// nil when the store or the bucket has no object lock.
	RetainUntil *time.Time
}
